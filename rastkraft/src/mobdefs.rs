pub fn by_name(name: &str) -> usize {
    MOBS.iter().position(|m| m.name == name).unwrap_or_else(|| panic!("нет моба {name}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fifty_friendly_fifty_hostile() {
        assert_eq!(MOBS.iter().filter(|m| m.friendly).count(), 50);
        assert_eq!(MOBS.iter().filter(|m| !m.friendly).count(), 50);
        let mut names: Vec<_> = MOBS.iter().map(|m| m.name).collect();
        names.sort();
        names.dedup();
        assert_eq!(names.len(), 100);
        let mut drops: Vec<_> = MOBS.iter().map(|m| m.drop_name).collect();
        drops.sort();
        drops.dedup();
        assert_eq!(drops.len(), 100, "у каждого моба уникальный трофей");
    }
}
