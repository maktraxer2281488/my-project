#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Plan {
    Biped,
    Quad,
    Slime,
    Bird,
    Spider,
    Fish,
    Wisp,
    Golem,
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Hab {
    Meadow,
    Desert,
    Taiga,
    Ocean,
    Heaven,
    Cave,
    Night,
    Village,
}

pub const BURNS: u16 = 1;
pub const FLY: u16 = 2;
pub const SWIM: u16 = 4;
pub const HOP: u16 = 8;
pub const GLOW: u16 = 16;
pub const RANGED: u16 = 32;
pub const NEUTRAL: u16 = 64;

#[derive(Clone, Copy, PartialEq, Debug)]
pub enum DropKind {
    Mat,
    Food(u8, Eff, f32),
}

/// Обычный дополнительный дроп.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Extra {
    None,
    Beef,
    Chicken,
    Mutton,
    Fish,
    Leather,
    Fur,
    Bone,
    Feather,
    Slime,
    Thread,
    Coal,
    Gold,
    HeavenDust,
    Egg,
}

#[derive(Clone, Copy, Debug)]
pub struct MobDef {
    pub name: &'static str,
    pub friendly: bool,
    pub plan: Plan,
    pub scale: f32,
    pub c1: (u8, u8, u8),
    pub c2: (u8, u8, u8),
    pub c3: (u8, u8, u8),
    pub hp: f32,
    pub dmg: f32,
    pub speed: f32,
    pub hab: Hab,
    pub flags: u16,
    pub drop_name: &'static str,
    pub drop_icon: Icon,
    pub drop_col: (u8, u8, u8),
    pub drop_kind: DropKind,
    pub extra: Extra,
}

#[allow(clippy::too_many_arguments)]
const fn m(
    name: &'static str,
    friendly: bool,
    plan: Plan,
    scale: f32,
    c1: (u8, u8, u8),
    c2: (u8, u8, u8),
    c3: (u8, u8, u8),
    hp: f32,
    dmg: f32,
    speed: f32,
    hab: Hab,
    flags: u16,
    drop_name: &'static str,
    drop_icon: Icon,
    drop_col: (u8, u8, u8),
    drop_kind: DropKind,
    extra: Extra,
) -> MobDef {
    MobDef { name, friendly, plan, scale, c1, c2, c3, hp, dmg, speed, hab, flags, drop_name, drop_icon, drop_col, drop_kind, extra }
}

