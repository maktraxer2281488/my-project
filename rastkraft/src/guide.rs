/// Последняя глава: все рецепты по станциям (собирается из таблицы).
pub fn all_recipes_text() -> Vec<String> {
    let mut v = vec!["Все предметы, которые можно сделать, и из чего. Нажмите вкладку «Все» и найдите название — там картинки и кнопка «Сделать».".to_string()];
    for st in [Station::Hand, Station::Workbench, Station::Furnace, Station::Cauldron, Station::Anvil] {
        v.push(String::new());
        v.push(format!("== {} ==", match st {
            Station::Hand => "В руках",
            Station::Workbench => "Верстак",
            Station::Furnace => "Печь",
            Station::Cauldron => "Котёл",
            Station::Anvil => "Наковальня",
        }));
        for r in crafting::recipes().iter().filter(|r| r.station == st) {
            let ins: Vec<String> = r.ins.iter().map(|(it, n)| format!("{} ×{n}", it.name())).collect();
            let out = if r.out.1 > 1 { format!("{} ×{}", r.out.0.name(), r.out.1) } else { r.out.0.name().to_string() };
            v.push(format!("{out} — {}", ins.join(", ")));
        }
    }
    v
}
